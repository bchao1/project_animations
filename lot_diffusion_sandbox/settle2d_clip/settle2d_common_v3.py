"""Shared data, timeline, token motion and geometry for the 2D settle clip, v3 (sim2d_v3.py, render_tiles_v3.py,
animation_lot_settle2d_v3.py).

v3 (user feedback on v2: real fluid starts spreading the moment it lands, not after a pause): no "sand castle"
phase — friction is low from the start, and the hydrostatic push and jitter act from the first landing, but only
on landed particles (resting on the pile, slow vertically), with the surface-height map built from landed
particles only, so cubes in flight still fall straight down. Damping rises earlier (SETTLE 6.3–7.3 s, 2 /s)
and the push stays constant, so the sloshing between the walls dies out by ≈ 8 s (sweep scratch/sweep3/a).

v2 (user feedback on v1: the top should end flat, by normal fluid flattening, no lattice snap): disks get ±20% random
sizes (equal disks crystallise and a one-row step in a crystal never flows away), the hydrostatic push stays on and
grows instead of halving, the jitter keeps 70% to the end, lighter damping. Surface std 1.18 → 0.40 rows; the drawn
squares keep one size.

2D version of ../spacetime_clip (v13 logic): six LoT-FLUX.2 4B images, each 64 × 64 tokens at full resolution.
Story per image: generated image (noise → image) → its LoT layout, every token filled with the image's mean colour
over the token's patch → every token shrinks to one 1 × 1 token (keeping its colour) → the squares fall under gravity
(2D position-based dynamics, same recipe as spacetime_clip/sim_physics_v2.py: random release, contacts, floor + walls,
friction high → ~0, hydrostatic push, light viscosity, keeps moving to the end) → the pile flattens to the height
n / 64 rows = the token fraction of the full-resolution 4,096 → the count collapses onto that tick, and the speedup
appears under the image.

Data: ../data/img/img_<id>_<source>_generated_4b.png + exact leaves ../data/layouts/img_<id>_<source>.json
(images_index.json; only layouts with 25–35% of the 4,096 tokens). Speedup ≈ Amdahl fit (1/s = a + (1 − a) n/4096,
a = 0.215) of the paper's per-image LoT-FLUX.2 4B timings (Fig. 21: 758 → 2.8×, 765 → 2.9×, 1,076 → 2.4×,
1,111 → 2.2×, 1,592 → 1.9×, 1,675 → 1.9×, 1,752 → 1.8×), same fit as ../arcade_clip.
"""
