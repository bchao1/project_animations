DURATION, FPS = 14.5, 60

# ------------------------------------------------------------------ timeline (s)
GENERATE = (0.2, 1.7)             # noise → generated image (tile i starts STAGGER · i later)
TOKENIZE = (2.0, 3.0)             # diagonal sweep: image → mean-colour token layout
STAGGER = 0.08
SHRINK = (3.7, 4.5)               # every token → one 1 × 1 token at a cell of its footprint
FALL = (4.6, DURATION)            # physics to the end of the clip
RELEASE, GRAV = 0.6, 140.0        # release window (s); gravity (cells / s²)
LIQUEFY = (4.6, 4.8)              # v3: fluid from the first landing (friction low, push + jitter on)
VLAND = 6.0                       # |v_y| (cells / s) below which a touching particle counts as landed
SETTLE = (6.3, 7.3)               # damping rises a little: the flow calms but the surface keeps moving
PRESSURE_GAIN, JITTER = 200.0, 6.0
PRESSURE_END = 0.0               # fraction of the hydrostatic push lost by the end of SETTLE (−1: doubles)
JITTER_END = 0.7                  # fraction of the jitter kept after SETTLE
VISC_END = 2.0                    # damping rate (1 / s) after SETTLE
POOL = 3                          # surface-height smoothing window (columns)
POLY = 0.2                        # disk-size spread (± fraction of D): no crystal, so the surface can flow flat
SURF = 0.0                        # e-folding depth (cells) of the slope push below the surface; 0 = whole column
D = 1.05                          # particle diameter (cells), calibrated so the rest level ≈ n / 64 rows
COLLAPSE = (9.8, 10.6)            # count → % at the level tick
SPEED_T = 10.8                    # speedups appear
CAPS = [(0.0, "Six images generated by LoT Diffusion…"),
        (2.0, "…each from its own token layout."),
        (3.7, "Now shrink every token to a single cell…"),
        (6.3, "…and let them settle: the height is the token fraction."),
        (SPEED_T, "25–35% of the tokens, 2.1–2.4× faster.")]       # speedup() of 1,420 / 1,024 tokens


def smooth(x):
    x = np.clip(x, 0.0, 1.0)
    return x * x * (3 - 2 * x)


def ease(t, a, b):
    return float(smooth((t - a) / (b - a)))


def friction(t):
    return 30.0 - (30.0 - 0.3) * ease(t, *LIQUEFY)


def viscosity(t):
    return 0.3 + (VISC_END - 0.3) * ease(t, *SETTLE)


def pressure(t):
    return PRESSURE_GAIN * ease(t, *LIQUEFY) * (1 - PRESSURE_END * ease(t, *SETTLE))


def jitter(t):
    """Horizontal velocity noise (cells / s / √s): on while fluid, JITTER_END of it after SETTLE."""
    return JITTER * ease(t, *LIQUEFY) * (1 - (1 - JITTER_END) * ease(t, *SETTLE))


def speedup(n, a=0.215):
    return 1.0 / (a + (1 - a) * n / FULL)


# ------------------------------------------------------------------ geometry (manim units ↔ 1080p pixels)
PX = 1080 / 8.0                   # pixels per manim unit
CELL = 5.8                        # pixels per token cell at 1080p → tile = 371 px = 2.75 units
TILE = N * CELL / PX
CENTERS = [(x, y) for y in (1.83, -1.33) for x in (-4.25, 0.25, 4.75)]
M = 0.1                           # token margin (fraction of a cell) on every side


def to_px(x, y):
    return (x + 64 / 9) * PX, (4.0 - y) * PX


def tile_origin_px(i):
    """Top-left pixel of tile i at 1080p."""
    cx, cy = CENTERS[i]
    px, py = to_px(cx, cy)
    return px - N * CELL / 2, py - N * CELL / 2


def level_y(i, level):
    """manim y of `level` rows above tile i's floor."""
    return CENTERS[i][1] - TILE / 2 + level * TILE / N


# ------------------------------------------------------------------ data
def load_item(i):
    iid, src, _ = ITEMS[i]
    img = Image.open(os.path.join(ROOT, "data", "img", f"img_{iid}_{src}_generated_4b.png")).convert("RGB")
    rects = np.array(json.load(open(os.path.join(ROOT, "data", "layouts", f"img_{iid}_{src}.json")))["rects"], int)
    return img, rects                              # rects: (y0, y1, x0, x1) in token cells


class Tokens:
    """All tokens of image i: layout boxes, unit cells and mean colours (cell space, y down from the top)."""

    def __init__(self, i):
        img, R = load_item(i)
        self.img = img
        a = np.asarray(img.resize((N * 16, N * 16), Image.BOX), np.float64)
        cell = a.reshape(N, 16, N, 16, 3).mean((1, 3))
        y0, y1, x0, x1 = R.T
        self.n = len(R)
        self.rects = R
        self.color = np.array([cell[a0:a1, b0:b1].mean((0, 1)) for a0, a1, b0, b1 in R])
        self.lay_lo = np.c_[x0 + M, y0 + M]
        self.lay_hi = np.c_[x1 - M, y1 - M]
        rs, cs = y0 + (y1 - y0 - 1) // 2, x0 + (x1 - x0 - 1) // 2   # top-left-of-centre cell of the footprint
        self.cell = np.c_[rs, cs]
        self.unit_lo = np.c_[cs + M, rs + M]
        self.unit_hi = np.c_[cs + 1 - M, rs + 1 - M]
        self.level = self.n / N                         # rest height in rows
        self.frac = self.n / FULL


def counts():
    return [len(load_item(i)[1]) for i in range(NI)]
